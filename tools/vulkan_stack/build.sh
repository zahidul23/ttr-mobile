#!/usr/bin/env bash
# Build the OpenGL-on-Vulkan stack (Mesa zink + the X11 client pieces it needs) for Android arm64.
# Run inside WSL Ubuntu 24.04:  bash tools/vulkan_stack/build.sh [stage...]
# Stages: prefix xcb x11xcb xshmfence libdrm xxf86vm mesa vkloader shmem package   (default: all, in order)
# Output: build/vulkan-stack/out/lib (stripped .so files ready to package).
set -euo pipefail

REPO=$(cd "$(dirname "$0")/../.." && pwd)
WORK=${WORK:-/opt/ttrbuild}
NDK=$WORK/android-ndk-r28c
TC=$NDK/toolchains/llvm/prebuilt/linux-x86_64
API=29
CC=$TC/bin/aarch64-linux-android$API-clang
CXX=$TC/bin/aarch64-linux-android$API-clang++
STRIP=$TC/bin/llvm-strip
PREFIX=$WORK/prefix
GEN=$WORK/gen
OUT=$REPO/build/vulkan-stack/out
MESON=/opt/mesonenv/bin/meson
X11SRC=$REPO/.tools/termux-x11-source/lorie/src/main/cpp
LIBS=$REPO/build/linux-libraries
CFLAGS_COMMON="-O2 -fPIC -I$PREFIX/include"
export PKG_CONFIG_LIBDIR=$PREFIX/lib/pkgconfig PKG_CONFIG_SYSROOT_DIR=

log() { echo "=== $*"; }
pc() {  # pc NAME VERSION LIBS [REQUIRES]
  mkdir -p "$PREFIX/lib/pkgconfig"
  cat > "$PREFIX/lib/pkgconfig/$1.pc" <<EOF
prefix=$PREFIX
libdir=\${prefix}/lib
includedir=\${prefix}/include
Name: $1
Description: $1 (TTR Mobile Android build)
Version: $2
Requires: ${4:-}
Libs: -L\${libdir} $3
Cflags: -I\${includedir}
EOF
}

# The X11 client libraries the app already ships (built by tools/build_x11_libraries.py), their headers, and
# xorgproto; Mesa links against these so Wine and Mesa share one X11 stack.
stage_prefix() {
  log "prefix: existing X11 libraries, headers, xorgproto"
  mkdir -p "$PREFIX/lib" "$PREFIX/include/xcb" "$PREFIX/include/X11/extensions"
  for l in libX11 libxcb libXau libXdmcp libXext libXfixes libXrender libXrandr; do cp "$LIBS/native/$l.so" "$PREFIX/lib/"; done
  cp -r "$X11SRC/xorgproto/include/." "$PREFIX/include/"
  cp -r "$LIBS/libx11/include/X11/." "$PREFIX/include/X11/"
  cp "$PREFIX/include/X11/XTtrLocale.h" "$PREFIX/include/X11/Xlocale.h" 2>/dev/null || true
  cp "$LIBS"/include/xcb/*.h "$PREFIX/include/xcb/"
  cp "$X11SRC"/libxau/include/X11/*.h "$PREFIX/include/X11/"
  cp "$X11SRC"/libxdmcp/include/X11/*.h "$PREFIX/include/X11/" 2>/dev/null || true
  for d in libxext libxfixes libxrender libxrandr; do cp -r "$REPO/.tools/$d-source/include/X11/." "$PREFIX/include/X11/"; done
  # XlibConf.h is generated by the libX11 build; Android's libX11 is thread-safe.
  [ -f "$PREFIX/include/X11/XlibConf.h" ] || printf '#ifndef _XLIBCONF_H_\n#define _XLIBCONF_H_\n#define XTHREADS 1\n#define XUSE_MTSAFE_API 1\n#endif\n' > "$PREFIX/include/X11/XlibConf.h"
  pc xproto 7.0.33 "" ; pc xorgproto 2024.1 ""
  for p in glproto:1.4.17 dri2proto:2.8 dri3proto:1.4 presentproto:1.4 xf86vidmodeproto:2.3.1 fixesproto:6.1 randrproto:1.6.0 xextproto:7.3.0 renderproto:0.11.1 kbproto:1.0.7; do pc "${p%%:*}" "${p##*:}" ""; done
  pc xau 1.0.11 "-lXau"; pc xdmcp 1.1.5 "-lXdmcp"
  pc xcb 1.17.0 "-lxcb" "xau"; pc x11 1.8.10 "-lX11" "xcb"
  pc xext 1.3.6 "-lXext" "x11"; pc xfixes 6.0.1 "-lXfixes" "x11"; pc xrender 0.9.12 "-lXrender" "x11"; pc xrandr 1.5.4 "-lXrandr" "x11 xrender"
}

# XCB extension libraries, generated from the same xcbproto as the app's libxcb.
stage_xcb() {
  log "xcb extensions"
  mkdir -p "$GEN/xcb"; cd "$GEN/xcb"
  local proto=$REPO/.tools/xcbproto-source xcbsrc=$REPO/.tools/libxcb-source/src
  build_ext() {  # name deps...
    local name=$1; shift
    PYTHONPATH=$proto python3 "$xcbsrc/c_client.py" -p "$proto" -c "TTR Mobile" -l XCB -s 3 "$proto/src/$name.xml"
    cp "$name.h" "$PREFIX/include/xcb/"
    local links="" reqs=""; for d in "$@"; do links+=" -lxcb-$d"; reqs+=" xcb-$d"; done
    $CC $CFLAGS_COMMON -I"$PREFIX/include/xcb" -I"$xcbsrc" -shared -Wl,-soname,libxcb-$name.so -o "$PREFIX/lib/libxcb-$name.so" "$name.c" -L"$PREFIX/lib" $links -lxcb
    pc "xcb-$name" 1.17.0 "-lxcb-$name" "xcb$reqs"
  }
  build_ext render; build_ext shape; build_ext xfixes render shape; build_ext randr render
  build_ext sync; build_ext dri3; build_ext present randr xfixes sync render shape dri3; build_ext dri2; build_ext glx; build_ext shm
}

# libX11-xcb: XGetXCBConnection and XSetEventQueueOwner from libX11's own source.
stage_x11xcb() {
  log "libX11-xcb"
  $CC $CFLAGS_COMMON -I"$LIBS/libx11/include" -I"$LIBS/libx11/include/X11" -I"$LIBS/libx11/src" -I"$LIBS/include" -DHAVE_CONFIG_H -include "$LIBS/include/config.h" \
    -shared -Wl,-soname,libX11-xcb.so -o "$PREFIX/lib/libX11-xcb.so" "$LIBS/libx11/src/x11_xcb.c" -L"$PREFIX/lib" -lX11 -lxcb
  pc x11-xcb 1.8.10 "-lX11-xcb" "x11 xcb"
}

# libxshmfence (futex variant, as Termux:X11's server expects); memfd_create via syscall on API 29.
stage_xshmfence() {
  log "libxshmfence"
  mkdir -p "$GEN/xshmfence"; cd "$GEN/xshmfence"
  printf '#include <limits.h>\n' > values.h
  printf '#include <unistd.h>\n#include <sys/syscall.h>\n#include <linux/memfd.h>\nstatic inline int memfd_create(const char *n, unsigned f) { return syscall(__NR_memfd_create, n, f); }\n' > memfd.h
  local src=$X11SRC/libxshmfence/src
  $CC $CFLAGS_COMMON -I. -include memfd.h -DHAVE_FUTEX -DHAVE_MEMFD_CREATE -DSHMDIR='"/data/local/tmp"' -DMAXINT=INT_MAX \
    -shared -Wl,-soname,libxshmfence.so -o "$PREFIX/lib/libxshmfence.so" "$src/xshmfence_alloc.c" "$src/xshmfence_futex.c"
  mkdir -p "$PREFIX/include/X11"; cp "$src/xshmfence.h" "$PREFIX/include/X11/"
  pc xshmfence 1.3.2 "-lxshmfence"
}

fetch() {  # fetch URL SHA256 [NAME] -> $WORK/src/NAME (default: the URL's file name), verified
  mkdir -p "$WORK/src"; local f=$WORK/src/${3:-$(basename "$1")}
  [ -f "$f" ] || wget -q -O "$f" "$1"
  echo "$2  $f" | sha256sum -c --quiet
}

# libdrm core only (no GPU-specific helpers): Mesa's DRI3 path needs its format/modifier helpers.
LIBDRM_VERSION=2.4.124
LIBDRM_SHA256=ac36293f61ca4aafaf4b16a2a7afff312aa4f5c37c9fbd797de9e3c0863ca379
stage_libdrm() {
  log "libdrm $LIBDRM_VERSION"
  fetch "https://dri.freedesktop.org/libdrm/libdrm-$LIBDRM_VERSION.tar.xz" "$LIBDRM_SHA256"
  rm -rf "$GEN/libdrm" && mkdir -p "$GEN" && tar -xf "$WORK/src/libdrm-$LIBDRM_VERSION.tar.xz" -C "$GEN" && mv "$GEN/libdrm-$LIBDRM_VERSION" "$GEN/libdrm"
  cd "$GEN/libdrm"
  $MESON setup build --cross-file "$WORK/android-aarch64.ini" --prefix "$PREFIX" --libdir lib --buildtype release \
    -Dintel=disabled -Dradeon=disabled -Damdgpu=disabled -Dnouveau=disabled -Dvmwgfx=disabled -Domap=disabled \
    -Dexynos=disabled -Dfreedreno=disabled -Dtegra=disabled -Dvc4=disabled -Detnaviv=disabled -Dcairo-tests=disabled \
    -Dman-pages=disabled -Dvalgrind=disabled -Dtests=false -Dinstall-test-programs=false -Dudev=false >/dev/null
  $MESON compile -C build >/dev/null && $MESON install -C build >/dev/null
}

