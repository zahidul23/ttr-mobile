}

# Mesa: zink (OpenGL on Vulkan) with GLX for X11 only. No LLVM, EGL, GBM, glvnd or other drivers.
# Android fixes come from Termux's Mesa package (pinned commit, checked by hash); its anon-file temp-dir patch is left
# out because our runtime always sets XDG_RUNTIME_DIR.
# 25.1.x: the newest Mesa whose zink accepts PowerVR drivers (e.g. the Moto G Power's BXM-8-256 through the
# GameNative wrapper). 25.2 requires VK_KHR_dynamic_rendering and 26.x VK_KHR_maintenance5, which those drivers lack.
MESA_VERSION=25.1.5
MESA_SHA256=3c4f6b10ff6ee950d0ec6ea733cc6e6d34c569454e3d39a9b276de9115a3b363
TERMUX_COMMIT=b2f856ec2882d51cf0841f543a06aa392f1470e4
MESA_PATCHES="
b7eb87464cdeba43a51db092322976edf9019501c91b6722d3db902e9ec02999 0000-disable-android-detection.patch
58d8672360c8c38ec7bb22785685f39c68de9b81ee3c48e5141f2ec35efe1111 0002-fix-for-getprogname.patch
ac4474bb3745727aa240a027511d88733aa3ad30f7816c32bc98de16f46bc726 0004-do-not-check-xlocale.patch
9ecdfc951cb60331250c1a4d410a797bbbc2d945e399b6d8dfdf6d33760db721 0006-wsi-no-pthread_cancel.patch
d60ab74e945e0ce0e18b9e59ed463fc201feaad6766e75bfb9d1e95cb657c0aa 0007-use-mtx_t-operations-in-turnip.patch
0801ddd7e3eb56abee516e7194b618b93a1abd04be3a2fa7f304374674df4352 0008-workaround-fortify-check.patch
c9f7d115cc507dda06b4c24b971dd174360a18dcc713c84e7a940d204651162c 0014-replace-turnip-wait_timestamp_safe-assert.patch
294c18de96d951be29747a1fe1355c124ac141263f0879c5daa6ff0edfd9d506 0016-define-reallocarray.patch"
# Turnip (Mesa's Adreno Vulkan driver) also learns the Adreno 710/720 from Termux's later patch set.
TURNIP_PATCH_COMMIT=21393bf9c611c586fde4c28f07f17c96aab459ec
TURNIP_PATCH="d824880ba2856e072693f7c52183d423c21231ab8c51d31417973bb1b3c621e1 0017-unofficial_support_adreno_710_720.patch"
stage_mesa() {
  log "mesa $MESA_VERSION"
  fetch "https://archive.mesa3d.org/mesa-$MESA_VERSION.tar.xz" "$MESA_SHA256"
  rm -rf "$GEN/mesa" && tar -xf "$WORK/src/mesa-$MESA_VERSION.tar.xz" -C "$GEN" && mv "$GEN/mesa-$MESA_VERSION" "$GEN/mesa"
  cd "$GEN/mesa" && rm -rf subprojects/*.wrap.disabled
  while read -r sum name; do
    [ -n "$name" ] || continue
    fetch "https://raw.githubusercontent.com/termux/termux-packages/$TERMUX_COMMIT/packages/mesa/$name" "$sum" "termux-${TERMUX_COMMIT:0:8}-$name"
    patch -p1 --silent < "$WORK/src/termux-${TERMUX_COMMIT:0:8}-$name"
  done <<< "$MESA_PATCHES"
  read -r tsum tname <<< "$TURNIP_PATCH"
  fetch "https://raw.githubusercontent.com/termux/termux-packages/$TURNIP_PATCH_COMMIT/packages/mesa/$tname" "$tsum" "termux-${TURNIP_PATCH_COMMIT:0:8}-$tname"
  patch -p1 --fuzz=3 < "$WORK/src/termux-${TURNIP_PATCH_COMMIT:0:8}-$tname"
  # No bundled sub-projects (like Termux): optional extras such as libarchive are simply left out.
  $MESON setup build --cross-file "$WORK/android-aarch64.ini" --prefix "$PREFIX" --libdir lib --buildtype release -Db_ndebug=true \
    --wrap-mode=nofallback -Dplatforms=x11 -Dgallium-drivers=zink -Dvulkan-drivers=freedreno -Dfreedreno-kmds=msm,kgsl -Dglx=dri -Dopengl=true -Degl=disabled -Dgbm=disabled \
    -Dgles1=disabled -Dgles2=disabled -Dglvnd=disabled -Dllvm=disabled -Dxmlconfig=disabled -Dzstd=disabled -Dexpat=disabled \
    -Dvalgrind=disabled -Dlibunwind=disabled -Dlmsensors=disabled -Dbuild-tests=false -Dtools= -Dvulkan-layers= \
    -Dgallium-va=disabled -Dandroid-libbacktrace=disabled -Dintel-rt=disabled \
    -Dmicrosoft-clc=disabled -Dgallium-rusticl=false 2>&1 | tail -40
  $MESON compile -C build 2>&1 | grep -E "error|FAILED|warning: unused" | head -40 || true
  $MESON install -C build >/dev/null
}

# Khronos Vulkan loader (libvulkan.so.1), built as for Linux with the NDK compiler like Termux's vulkan-loader-generic.
# Android's own loader only loads the phone's driver; this one honours VK_ICD_FILENAMES (our wrapper or Turnip).
VK_VERSION=1.4.325
VK_HEADERS_SHA256=5743da4e203456ef0a0d17950d448b4f70e93a19abdc547aa33c15482b4fec17
VK_LOADER_SHA256=029f58547cab96eb7b2c2b993e241b69635415c49cf8f8e7a610ad9f1ee3ce73
stage_vkloader() {
  log "Vulkan loader $VK_VERSION"
  fetch "https://github.com/KhronosGroup/Vulkan-Headers/archive/refs/tags/v$VK_VERSION.tar.gz" "$VK_HEADERS_SHA256" "Vulkan-Headers-$VK_VERSION.tar.gz"
  fetch "https://github.com/KhronosGroup/Vulkan-Loader/archive/refs/tags/v$VK_VERSION.tar.gz" "$VK_LOADER_SHA256" "Vulkan-Loader-$VK_VERSION.tar.gz"
  rm -rf "$GEN/vk-headers" "$GEN/vk-loader" && mkdir -p "$GEN/vk-headers" "$GEN/vk-loader"
  tar -xf "$WORK/src/Vulkan-Headers-$VK_VERSION.tar.gz" -C "$GEN/vk-headers" --strip-components 1
  tar -xf "$WORK/src/Vulkan-Loader-$VK_VERSION.tar.gz" -C "$GEN/vk-loader" --strip-components 1
  cmake -S "$GEN/vk-headers" -B "$GEN/vk-headers/build" -DCMAKE_INSTALL_PREFIX="$PREFIX" >/dev/null && cmake --install "$GEN/vk-headers/build" >/dev/null
  cmake -S "$GEN/vk-loader" -B "$GEN/vk-loader/build" -DCMAKE_SYSTEM_NAME=Linux -DCMAKE_SYSTEM_PROCESSOR=aarch64 \
    -DCMAKE_C_COMPILER="$CC" -DCMAKE_CXX_COMPILER="$CXX" -DCMAKE_ASM_COMPILER="$CC" -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_INSTALL_LIBDIR=lib -DCMAKE_PREFIX_PATH="$PREFIX" -DVULKAN_HEADERS_INSTALL_DIR="$PREFIX" \
    -DCMAKE_C_FLAGS="-I$PREFIX/include" -DBUILD_WSI_XCB_SUPPORT=ON -DBUILD_WSI_XLIB_SUPPORT=ON -DBUILD_WSI_WAYLAND_SUPPORT=OFF \
    -DBUILD_WSI_DIRECTFB_SUPPORT=OFF -DBUILD_TESTS=OFF 2>&1 | grep -iE "error|warn" | head -20 || true
  cmake --build "$GEN/vk-loader/build" -j"$(nproc)" 2>&1 | grep -E "error|FAILED" | head -20 || true
  cmake --install "$GEN/vk-loader/build" >/dev/null
}

# libandroid-shmem (System V shared memory on Android), needed by GameNative's Vulkan wrapper.
stage_shmem() {
  log "libandroid-shmem"
  local src=$REPO/.tools/android-shmem-source
  # Key files go in $TMPDIR, which the app sets to its own Wine temp folder, so no package name is built in
  # (Android's libc has no _PATH_TMP).
  mkdir -p "$GEN/shmem"
  sed 's|sprintf(symlink_path, ASHV_KEY_SYMLINK_PATH, key);|snprintf(symlink_path, sizeof(symlink_path), "%s/ashv_key_%d", getenv("TMPDIR") ? getenv("TMPDIR") : "/data/local/tmp", key);|' \
    "$src/shmem.c" > "$GEN/shmem/shmem.c"
  grep -q 'getenv("TMPDIR")' "$GEN/shmem/shmem.c" || { echo "shmem.c patch did not apply"; exit 1; }
  $CC -O2 -fPIC -std=c11 -D'_PATH_TMP="/data/local/tmp/"' -I"$src" -shared -Wl,--version-script="$src/exports.txt" -Wl,-soname,libandroid-shmem.so \
    -o "$PREFIX/lib/libandroid-shmem.so" "$GEN/shmem/shmem.c" -llog -landroid
}

# Everything the app downloads, stripped, as build/vulkan-stack/vulkan-stack.tar.zst:
# lib/ (Mesa, Vulkan loader, X11 add-ons, C++ runtime), lib/dri/zink_dri.so, licenses/.
STACK_LIBS="libGL.so.1 libgallium-$MESA_VERSION.so libvulkan.so.1 libdrm.so libxshmfence.so libX11-xcb.so libXxf86vm.so
libxcb-render.so libxcb-shape.so libxcb-xfixes.so libxcb-randr.so libxcb-sync.so libxcb-dri3.so libxcb-present.so
libxcb-dri2.so libxcb-glx.so libxcb-shm.so libandroid-shmem.so libvulkan_freedreno.so"
stage_package() {
  log "package"
  rm -rf "$OUT" && mkdir -p "$OUT/lib/dri" "$OUT/licenses"
  for l in $STACK_LIBS; do cp -L "$PREFIX/lib/$l" "$OUT/lib/$l"; done
  cp -L "$PREFIX/lib/dri/libdril_dri.so" "$OUT/lib/dri/zink_dri.so"
  cp "$TC/sysroot/usr/lib/aarch64-linux-android/libc++_shared.so" "$OUT/lib/"
  find "$OUT/lib" -name '*.so*' -exec "$STRIP" --strip-unneeded {} \;
  cp "$GEN/mesa/docs/license.rst" "$OUT/licenses/mesa.rst"
  cp "$GEN/vk-loader/LICENSE.txt" "$OUT/licenses/vulkan-loader.txt"
  cp "$REPO/.tools/android-shmem-source/LICENSE" "$OUT/licenses/android-shmem.txt"
  cp "$REPO/.tools/libxcb-source/COPYING" "$OUT/licenses/libxcb.txt"
  cp "$GEN/libdrm/core/LICENSE" "$OUT/licenses/libdrm.txt" 2>/dev/null || true
  local archive=$REPO/build/vulkan-stack/vulkan-stack.tar.zst
  tar -C "$OUT" --owner=0 --group=0 --sort=name --mtime=@0 -cf - lib licenses | zstd -19 -q -f -o "$archive"
  du -sh "$OUT/lib"; ls -la "$archive"; sha256sum "$archive"
}

cross_file() {
  cat > "$WORK/android-aarch64.ini" <<EOF
[binaries]
c = '$CC'
cpp = '$CXX'
ar = '$TC/bin/llvm-ar'
strip = '$STRIP'
pkg-config = 'pkg-config'
[host_machine]
system = 'linux'
cpu_family = 'aarch64'
cpu = 'armv8'
endian = 'little'
[built-in options]
c_args = ['-I$PREFIX/include']
cpp_args = ['-I$PREFIX/include']
c_link_args = ['-L$PREFIX/lib', '-Wl,--undefined-version']
cpp_link_args = ['-L$PREFIX/lib', '-static-libstdc++', '-Wl,--undefined-version']
EOF
}

stages=("$@"); [ ${#stages[@]} -eq 0 ] && stages=(prefix xcb x11xcb xshmfence libdrm xxf86vm mesa vkloader shmem package)
cross_file
for s in "${stages[@]}"; do "stage_$s"; done
log "done: ${stages[*]}"
