  log "libXxf86vm $XXF86VM_VERSION"
  fetch "https://www.x.org/releases/individual/lib/libXxf86vm-$XXF86VM_VERSION.tar.xz" "$XXF86VM_SHA256"
  rm -rf "$GEN/xxf86vm" && mkdir -p "$GEN/xxf86vm" && tar -xf "$WORK/src/libXxf86vm-$XXF86VM_VERSION.tar.xz" -C "$GEN/xxf86vm" --strip-components 1
  cp "$GEN/xxf86vm/include/X11/extensions/xf86vmode.h" "$PREFIX/include/X11/extensions/"
